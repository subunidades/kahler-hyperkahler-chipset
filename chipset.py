"""Kähler + Hyperkähler chipset: pre-layout design model (Qiskit + transmon physics).

Dies
  Kähler die      : 2 flux-tunable transmons, 1 coupler  -> state space CP^3
  Hyperkähler die : 3 flux-tunable transmons, triangle    -> SU(2)-symmetric unit
Native gates: XY exchange (XXPlusYY) + CPhase, with virtual Z. The Heisenberg pair gate
exp(-iθ(XX+YY+ZZ)) = XY(4θ)·CPhase-type(RZZ 2θ), so the hyperkähler symmetry is
generated by gates the hardware actually has.
All frequencies/couplings below are ILLUSTRATIVE placeholders, to be replaced by the
chosen foundry's process data (E_J, E_C, capacitances).
Run: python chipset.py   (needs kahler_hyperkahler_qiskit.py, hyperkahler_unit.py alongside)
"""
